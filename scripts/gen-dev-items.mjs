// Writes scripts/dev-items.js: the paste-into-console script that fills slot 3's
// stash with every relic, gear base and consumable. The item catalog is baked
// in, so the script works on the deployed site as well as `npm run dev`.
// Usage: node scripts/gen-dev-items.mjs  (or `npm run dev:items`)
// Pass --check to fail instead of writing when the script is stale.
import { readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { rolldown } from 'rolldown';

const OUT = resolve('scripts/dev-items.js');
const check = process.argv.includes('--check');

const bundle = await rolldown({ input: resolve('src/dev/items-catalog.ts') });
const { output } = await bundle.generate({ format: 'esm', codeSplitting: false });
await bundle.close();
const { itemsCatalog } = await import(`data:text/javascript;base64,${Buffer.from(output[0].code).toString('base64')}`);
const catalog = itemsCatalog();

const script = `/*
 * GENERATED by scripts/gen-dev-items.mjs, so edit that, not this. Run
 * \`npm run dev:items\` after the item data changes.
 *
 * Paste this entire file into the browser console on npm run dev OR the
 * deployed game. It adds every relic (identified, and recorded in the codex),
 * one Epic piece of every gear base in its best material, and 10 of every
 * consumable (tonics included) to the stash of SLOT 3, then reloads.
 *
 * Slot 3 is used if it already holds a character; otherwise the character you
 * are playing is copied there first. Slot 1, the real save, is never written.
 * It edits the save in localStorage directly, so it needs no dev hooks.
 *
 * Reuse: __giveItems(25)   // quantity per consumable
 * Signed in with cloud saves on? The next sync may replace slot 3 with the
 * cloud copy, so play it straight after the reload.
 */
window.__giveItems = (quantity = 10) => {
  const CATALOG = ${JSON.stringify(catalog)};
  if (!Number.isSafeInteger(quantity) || quantity < 1 || quantity > 999) {
    throw new Error('Choose a whole-number quantity between 1 and 999.');
  }
  const keyFor = (n) => (n === 1 ? 'looting-simulator-save-v2' : \`looting-simulator-save-v2-s\${n}\`);
  const last = Number(localStorage.getItem('looting-simulator-slot')) || 1;
  const raw = localStorage.getItem(keyFor(3)) ?? localStorage.getItem(keyFor(last));
  if (!raw) throw new Error('No save found. Start a character first.');
  const state = JSON.parse(raw);

  let n = 0;
  const uid = () => Date.now().toString(36) + (n++).toString(36) + Math.floor(Math.random() * 46656).toString(36);
  const stash = state.stash.items;
  const stackOnto = (kind, ref, qty) => {
    const have = stash.find((i) => i.kind === kind && i.ref === ref);
    if (have) have.qty += qty;
    else stash.push({ uid: uid(), kind, ref, qty });
  };
  const gear = (baseId, materialId, extra) => stash.push({
    uid: uid(), kind: 'equipment', ref: baseId, qty: 1, materialId,
    rarity: 'Epic', ilvl: 16, affixes: [], identified: true, quality: 1, ...extra,
  });

  const life = (state.lifetime ??= {});
  life.uniquesSeen ??= [];
  life.uniquesKnown ??= [];
  let relics = 0;
  for (const r of CATALOG.relics) {
    if (r.kind === 'gear') {
      gear(r.baseId, r.materialId, { rarity: 'Legendary', ilvl: Math.max(r.minDepth, 6) * 2, quality: 1.15, uniqueId: r.id });
      relics++;
    }
    if (!life.uniquesSeen.includes(r.id)) life.uniquesSeen.push(r.id);
    if (!life.uniquesKnown.includes(r.id)) life.uniquesKnown.push(r.id);
  }
  for (const g of CATALOG.gear) gear(g.baseId, g.materialId);
  for (const id of CATALOG.consumables) stackOnto('consumable', id, quantity);

  localStorage.setItem(keyFor(3), JSON.stringify(state));
  localStorage.setItem('looting-simulator-slot', '3');
  // The running game would write its own copy back on the way out, so stop it.
  window.addEventListener('beforeunload', (e) => e.stopImmediatePropagation(), true);
  window.addEventListener('pagehide', (e) => e.stopImmediatePropagation(), true);
  console.log(\`Slot 3 stash: \${relics} relics, \${CATALOG.gear.length} gear pieces, \${quantity} each of \${CATALOG.consumables.length} consumables. Reloading...\`);
  setTimeout(() => location.reload(), 300);
};

window.__giveItems();
`;

if (check) {
  const current = await readFile(OUT, 'utf8').catch(() => '');
  if (current !== script) { console.error('scripts/dev-items.js is stale. Run npm run dev:items.'); process.exit(1); }
} else {
  await writeFile(OUT, script);
  console.log(`Wrote ${OUT}`);
}
