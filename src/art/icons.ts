import { ArtDef } from './raster';
import { rows, stamp, sym } from './helpers';

// 16×16 item icons. Ramp chars 1-4 are re-coloured per material at draw time;
// the defaults below are plain iron.
const PAL: Record<string, string> = {
  k: '#0e0a08', w: '#ffffff', h: '#7a5230', j: '#4a2e16', g: '#d0a040', r: '#d02828',
  e: '#16121a', p: '#e8dcbc', q: '#b8a078', t: '#8a7a5a', y: '#fff0a0', b: '#2a4a8a', l: '#c8d8ff',
  1: '#2a2a30', 2: '#55555e', 3: '#8a8a94', 4: '#c8c8d0',
};

const icon = (id: string, r: string[], extra: Record<string, string> = {}): ArtDef => ({ id, palette: { ...PAL, ...extra }, rows: r });

const SIGIL_TOKEN = sym(rows(`
  ........
  .....kkk
  ...kk111
  ..k11222
  .k122222
  .k122222
  k1222222
  k1222222
  k1222222
  k1222222
  .k122222
  .k122222
  ..k11222
  ...kk111
  .....kkk
  ........
`));

/**
 * One inscribed stone.
 *
 * All five used to be the same near-black pebble carrying a one-pixel scratch,
 * which made them a set of identical dark blobs in the pack: you could not tell
 * which sigil you had picked up without reading the tooltip. Two changes fix
 * that. The stone takes a tint of its own sigil's colour, so the five differ
 * before you have looked at anything; and the mark is a whole bold shape rather
 * than a glyph — a crescent, an eye, an arch — read at a glance and at 16px.
 */
const sigilIcon = (id: string, mark: string[], accent: string, dark: string, light: string): ArtDef => icon(
  id,
  stamp(SIGIL_TOKEN, mark, 4, 4),
  { k: '#0a090d', 1: dark, 2: light, s: accent },
);

